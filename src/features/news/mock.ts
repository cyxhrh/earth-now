export function createMockFeed(now = Date.now()): NewsFeed {
  const generatedAt = new Date(now).toISOString()
  const items: NewsItem[] = samples.map(([title, channel, name, lat, lng, theme], index) => {
    const id = `demo-${index + 1}`
    const summary = `这是一则虚构的交互演示，围绕“${theme}”展开。地点仅用于展示地球定位，内容不对应实际事件，也不代表机构声明或研究结论。`
    const picture = `/demo/${channel === 'AI' ? 'ai' : channel === '科技' ? 'technology' : 'world'}.svg`
    const withImage = index % 3 !== 2
    const short = index % 3 === 2
    return {
      id,
      title,
      channel,
      category: channel === '全球视野' ? '社会' : channel,
      summary,
      language: 'zh',
      location: { name, lat, lng, precision: 'city' },
      locationBasis: '虚构演示的示意地点，不是实际新闻发生地。',
      publishedAt: new Date(now - (index % 6 === 5 ? 36 : index + 0.3) * 3_600_000).toISOString(),
      sourceName: '地球此刻 · 虚构演示',
      sourceCount: 1,
      heat: 95 - index,
      isDemo: true,
      ...(withImage ? { imageUrl: picture } : {}),
      brief: {
        status: short ? 'limited' : 'ready',
        coverage: 'article',
        overview: summary,
        keyPoints: [
          '内容为项目编写的虚构样本，不能当作真实新闻。',
          `这则示例关注${theme}。`,
          '可以比较卡片、地点连线与阅读面板，体验完整浏览流程。',
        ],
        sections: short
          ? []
          : [
              {
                heading: '从一个地点开始探索',
                text: `把地球转向${name}，你会看到与这个示意地点相连的卡片。点击卡片会打开阅读面板，地球自动暂停，方便你阅读。关闭面板后，可以继续旋转、缩放，或切换到其他地区。这些位置用来演示交互，不是对现实事件的判断。`,
              },
              {
                heading: '一条速读应该说明什么',
                text: `以“${theme}”为例，真实模式会从原报道提取正文，再整理事件概览、关键事实和分节内容。资料不足时只保留简讯，不能用猜测填补背景；来源不可读时会明确说明。阅读时间按照实际文字估算，不为了达到两三分钟而重复内容。`,
              },
              {
                heading: '从演示切换到真实新闻',
                text: '此页面的文字和示意插图随项目提供，不需要新闻接口或模型密钥。若要浏览近期报道，请停止演示，在服务端配置文件中填写自己的模型密钥，再启动真实新闻模式。真实来源可能受网络、授权或页面结构变化影响；生成摘要需要结合原文核对，原文入口会保留。',
              },
            ],
        images: withImage
          ? [{ url: picture, caption: '地球此刻原创示意插图 · 非新闻现场照片' }]
          : [],
        readingMinutes: short ? 1 : 2,
        sourceUrl: `https://example.invalid/${id}`,
        generatedAt,
      },
    }
  })
  items.push({
    id: 'demo-global',
    title: '跨地区的话题，保留开放的视角',
    category: '社会',
    channel: '全球视野',
    summary: '这是没有单一发生地的虚构样本。跨地区内容保留在列表中，不在地球上强行添加坐标。',
    location: null,
    publishedAt: generatedAt,
    sourceName: '地球此刻 · 虚构演示',
    heat: 30,
    sourceCount: 1,
    isDemo: true,
  })
  return { items, generatedAt, mode: 'demo' }
}
